import { test, expect } from '@playwright/test';

test.describe('Project Management Flow', () => {
  test.beforeEach(async ({ page }) => {
    // Seed and bypass auth for testing, or use actual login UI:
    await page.goto('/login');
    await page.fill('input[name="email"]', 'fahad@gmail.com');
    await page.fill('input[name="password"]', '67890');
    await page.click('button[type="submit"]');
    await expect(page).toHaveURL('/projects');
  });

  test('can create a new project and view it in the list', async ({ page }) => {
    const testProjectName = `E2E Test Project ${Date.now()}`;
    
    await page.fill('input[name="name"]', testProjectName);
    await page.fill('input[name="description"]', 'Generated by Playwright');
    await page.click('button:has-text("Add Project")');

    // Assert optimistic UI and final state
    await expect(page.locator(`text=${testProjectName}`)).toBeVisible();
  });

  test('URL updates when searching', async ({ page }) => {
    await page.fill('input[name="q"]', 'Marketing');
    await page.click('button:has-text("Search")');

    // Assert URL query sync
    await expect(page).toHaveURL(/.*q=Marketing/);
  });
});